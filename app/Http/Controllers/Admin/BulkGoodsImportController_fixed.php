    private function parseDelimitedString($str)
    {
        if (empty($str)) {
            return [];
        }

        // ???????????????????????? ???????????????<?? ???????????????,??????: ?????????,????, ?,???????? ?? ?????????,????, ???????,???????????????? ???????,??, ?????????????? ???,????????
        return collect(preg_split('/[,;|\n\r]+/', $str))
            ->map(function ($item) {
                return trim($item);
            })
            ->filter()
            ->toArray();
    }

