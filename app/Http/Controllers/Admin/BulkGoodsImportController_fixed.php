                        if ($existingBySlug &&
                            $existingBySlug->name === $categoryName &&
                            $existingBySlug->parent_id == $parentId) {
                            $categoryId = $existingBySlug->id;
                            break;
                        }

                        // ?.?????? ???? ???????.???????,, ?????????????? ?????????????????<?? slug ?? ?????"?"??????????
                        $categorySlug = $baseSlug.'-'.$slugCounter;
                        $slugCounter++;
                    }

                    // ?.?????? ???? ?????????? ???????.???????????? ?????,????????????, ?????????????? ??????????
                    if (! $categoryId) {
                        try {
                            $newCategory = ShopCategory::create([
                                'name' => $categoryName,
