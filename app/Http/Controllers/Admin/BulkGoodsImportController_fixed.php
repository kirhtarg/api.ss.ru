                               '???????????????,?? ?????????????,???????,?? ???,???????,?????< XML ?"????????. '.
                               '?'??????????????, ?????????,?????<?? ?,?????? ???? ?????????<?,?< ?????? ?????????<?,?< ??????????????????????.';
            } elseif (strpos($errorMessage, 'parser error') !== false) {
                $errorMessage = '???????????? ???????????????? YML: '.$errorMessage;
            }

            return response()->json([
                'success' => false,
                'error' => $errorMessage,
                'message' => $errorMessage,
            ], 500);
        }
