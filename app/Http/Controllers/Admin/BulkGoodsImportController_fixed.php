        }

        // ???,???????,??????: <offers><offer>...</offer></offers> (?????? shop)
        if ($xml->getName() === 'offers' && isset($xml->offer)) {
            return 'offers_only';
        }

        // ???,???????,??????: <items><item>...</item></items> (?????? shop)
        if ($xml->getName() === 'items' && isset($xml->item)) {
            return 'items_only';
        }

