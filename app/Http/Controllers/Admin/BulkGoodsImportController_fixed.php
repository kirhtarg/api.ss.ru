                    'error' => "???????????? ???????????????? ?"??????: HTTP {$httpCode}",
                ], $httpCode);
            }

            if (empty($xmlContent)) {
                return response()->json([
                    'success' => false,
                    'error' => '?????? ???????,',
                ], 400);
            }

            // ???????????? XML ????????????????????
            $ymlData = $this->parseYMLContent($xmlContent);

            return response()->json([
                'success' => true,
                'ymlData' => $ymlData,
            ]);

        } catch (\Exception $e) {
            \Log::error('???????????? ???????????????? YML ???? URL', [
                'url' => $request->input('url'),
                'error' => $e->getMessage(),
                'trace' => $e->getTraceAsString(),
            ]);

            // ?????????????????? ?????????? ?????????,?????? ?????????????????? ???? ????????????
            $errorMessage = $e->getMessage();
