        return false;
    }

    /**
     * ???????????, ?,?????????< ???? ???????,?????????,???????<?. ???,???????,???? XML
     */
    private function parseAlternativeXMLStructure($xml, $structureType)
    {
        $categories = [];
        $offers = [];

        switch ($structureType) {
            case 'yml_catalog_custom':
                // ???,???????,??????: <yml_catalog><shop><items><item>...</item></items></shop></yml_catalog>
                if (isset($xml->shop->items->item)) {
                    foreach ($xml->shop->items->item as $item) {
                        $offerData = $this->parseCustomFormatItem($item, $categories);
                        if ($offerData) {
                            $offers[] = $offerData;
                        }
                    }
                }
                break;

            case 'offers_only':
                // ???,???????,??????: <offers><offer>...</offer></offers>
                if (isset($xml->offer)) {
                    foreach ($xml->offer as $offer) {
                        $offers[] = $this->parseStandardYMLOffer($offer);
                    }
                }
                break;

            case 'items_only':
                // ???,???????,??????: <items><item>...</item></items>
                if (isset($xml->item)) {
                    foreach ($xml->item as $item) {
                        $offerData = $this->parseCustomFormatItem($item, $categories);
                        if ($offerData) {
                            $offers[] = $offerData;
                        }
                    }
                }
                break;
        }

        return [$categories, $offers];
    }

