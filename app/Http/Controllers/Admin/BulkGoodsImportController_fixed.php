    private function trimGoodName($good, $nameTrimSymbol = null, $immutableFields = [], $nameFromData = null)
    {
        // ?.?????? ???????????? ?????????????? ???? ???????????? ?????? ?,???????? ???? ???????????? - ???????????? ???? ????????????
        if (empty($nameTrimSymbol) || empty(trim($nameTrimSymbol)) || ! $good || ! $good->id) {
