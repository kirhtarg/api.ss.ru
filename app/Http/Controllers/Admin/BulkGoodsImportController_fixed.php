                            // ???<?,?????????? ???????,?? ?????,???????????? ???? ?????????? ?? ?????????,?????? ?????? ??????
                            $fallbackQuery = ShopCategory::where('name', $categoryName);
                            if ($parentId) {
                                $fallbackQuery->where('parent_id', $parentId);
                            } else {
                                $fallbackQuery->whereNull('parent_id');
                            }
                            $fallbackCategory = $fallbackQuery->first();

                            if ($fallbackCategory) {
                                $categoryId = $fallbackCategory->id;
                            } else {
                                // ?.?????? ???? ??????????, ???????????????????? ???,?? ?????,????????????
                                continue;
                            }
                        }
                    }

