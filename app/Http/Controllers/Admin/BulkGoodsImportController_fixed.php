                    }
                } else {
                    // ???? ?????????????? ?????,????????????, ???????????????????? null
                    return null;
                }
            }

            $lastCategoryId = $categoryId;
            $parentId = $categoryId; // ?????????????????? ?????,???????????? ?????????, ???????????????? ?????? ?,????????????
        }

